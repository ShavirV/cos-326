-- Run everything as one transaction so the schema is created atomically:
-- if any statement fails, nothing is left half-built.
BEGIN;

-- Clean slate: allows the script to be re-run repeatedly while marking
-- without manual DROP statements. CASCADE removes dependent objects
-- (child tables, triggers, functions that reference the types) too.
DROP TABLE IF EXISTS DeletedIncidentAudit CASCADE;
DROP TABLE IF EXISTS NodeBreachIncident CASCADE;
DROP TABLE IF EXISTS NetworkIncident CASCADE;
DROP TABLE IF EXISTS Incident CASCADE;
DROP TABLE IF EXISTS EvidenceCatalog CASCADE;

DROP FUNCTION IF EXISTS audit_deleted_incident() CASCADE;
DROP FUNCTION IF EXISTS check_evidence_integrity() CASCADE;
DROP FUNCTION IF EXISTS validate_evidence_array(TEXT[]) CASCADE;
DROP FUNCTION IF EXISTS has_duplicate_hashes(TEXT[]) CASCADE;
DROP FUNCTION IF EXISTS is_hash_registered(TEXT) CASCADE;
DROP FUNCTION IF EXISTS format_investigator_name(InvestigatorName) CASCADE;

DROP TYPE IF EXISTS InvestigatorName CASCADE;
DROP TYPE IF EXISTS SeverityType CASCADE;
DROP DOMAIN IF EXISTS NodeIPType CASCADE;

DROP SEQUENCE IF EXISTS incident_seq;
DROP SEQUENCE IF EXISTS evidence_seq;


/* =====================================================================
   1. DOMAINS, ENUMS & SEQUENCES  (3 Marks)
   ===================================================================== */

-- NodeIPType (Domain): The spec asks for "valid standard IPv4 address
-- formatting (or text constrained to 15 characters)". We implement a
-- domain over VARCHAR(15) (the max length of a dotted-quad IPv4 string,
-- e.g. '255.255.255.255' = 15 chars) with a CHECK constraint that
-- validates the dotted-quad pattern using a regular expression. This
-- gives us both the length guard AND real IPv4 format validation,
-- satisfying the "or" in the spec as "and" (belt and braces).
-- NULL is explicitly allowed because a domain's CHECK is only evaluated
-- when a value is supplied; incidents may be created before a target IP
-- is confirmed.
CREATE DOMAIN NodeIPType AS VARCHAR(15)
    CHECK (
        VALUE IS NULL
        OR VALUE ~ '^(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)$'
    );
COMMENT ON DOMAIN NodeIPType IS 'IPv4 address stored as text, max 15 chars, validated by regex.';

-- SeverityType (ENUM): a small, closed set of values is a textbook use
-- case for PostgreSQL's native ENUM type. This is both storage-efficient
-- (stored as 4-byte OID internally) and self-documenting/order-aware
-- (LOW < MEDIUM < HIGH < CRITICAL follows declaration order, which is
-- handy if we ever want to ORDER BY severity).
CREATE TYPE SeverityType AS ENUM ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL');

-- InvestigatorName (UDT Composite): a ROW type bundling the three name
-- fields together. This is used as the data type of the
-- assigned_investigator column on NodeBreachIncident, and is also the
-- parameter type of format_investigator_name() below, demonstrating an
-- ORDBMS "structured type" as an attribute value in its own right,
-- rather than three separate scalar columns.
CREATE TYPE InvestigatorName AS (
    title       VARCHAR(10),
    first_name  VARCHAR(50),
    last_name   VARCHAR(50)
);

-- Sequences: PostgreSQL sequences are the standard way to generate
-- surrogate primary keys explicitly (rather than relying on the
-- shorthand SERIAL/IDENTITY), which is what the spec asks for by name
-- ("generated by sequence incident_seq" / "evidence_seq"). Using
-- explicit sequences also lets both a base table and its future
-- children draw from the SAME id-space, which matters for inheritance
-- (see note on Incident below).
CREATE SEQUENCE incident_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE evidence_seq START WITH 1 INCREMENT BY 1;


/* =====================================================================
   2. TABLE INHERITANCE & AUXILIARY TABLES  (5 Marks)
   ===================================================================== */

-- Incident (Base Table): the parent/superclass of the specialization
-- hierarchy. Every attribute listed here is automatically inherited by
-- NetworkIncident and NodeBreachIncident via INHERITS.
--
-- IMPORTANT PostgreSQL inheritance caveat (documented here rather than
-- hidden, per the "explain your reasoning" instruction): PRIMARY KEY /
-- UNIQUE constraints on a parent table are NOT automatically enforced
-- across the whole inheritance tree - each child gets its own separate
-- index. In other words, incident_id could in theory collide between a
-- NetworkIncident row and a NodeBreachIncident row. We accept this as a
-- known, documented limitation of native PG table inheritance (rather
-- than working around it with a trigger-based global-uniqueness check,
-- which is out of scope for this practical) and instead lean on the
-- fact that BOTH children draw their incident_id from the *same*
-- sequence (incident_seq), so in practice ids will not collide as long
-- as every INSERT uses DEFAULT / nextval('incident_seq') as shown in
-- InsertQueries.sql.
CREATE TABLE Incident (
    incident_id     INTEGER PRIMARY KEY DEFAULT nextval('incident_seq'),
    incident_code   VARCHAR(10) UNIQUE NOT NULL,
    target_ip       NodeIPType,
    severity        SeverityType,
    detected_at     TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE Incident IS 'Base/superclass table for the incident specialization hierarchy.';

-- NetworkIncident (Inherits Incident): specialization representing an
-- incident detected on a 5G network slice. INHERITS pulls in all of
-- Incident's columns (incident_id, incident_code, target_ip, severity,
-- detected_at) and adds slice_id + evidence_hashes.
--
-- evidence_hashes is a native PostgreSQL array (TEXT[]) - this is the
-- ORDBMS "collection-valued attribute" the spec calls for, letting a
-- single incident reference many forensic evidence files without a
-- separate join table.
CREATE TABLE NetworkIncident (
    slice_id         VARCHAR(20),
    evidence_hashes  TEXT[]
) INHERITS (Incident);
COMMENT ON TABLE NetworkIncident IS 'Incident subtype: a captured 5G network-slice event with linked PCAP evidence hashes.';

-- NodeBreachIncident (Inherits Incident): specialization representing a
-- compromised edge-computing node. Adds node_id, the composite UDT
-- assigned_investigator, and a containment flag.
CREATE TABLE NodeBreachIncident (
    node_id                 VARCHAR(20),
    assigned_investigator   InvestigatorName,
    is_contained             BOOLEAN NOT NULL DEFAULT FALSE
) INHERITS (Incident);
COMMENT ON TABLE NodeBreachIncident IS 'Incident subtype: a breached edge node, tracked with its assigned investigator.';

-- EvidenceCatalog (Table): the authoritative lookup/reference table of
-- forensic hashes that are considered "registered" (i.e. legitimately
-- captured and catalogued). NetworkIncident.evidence_hashes entries must
-- exist here - this is what check_evidence_integrity() validates below.
CREATE TABLE EvidenceCatalog (
    hash_id         INTEGER PRIMARY KEY DEFAULT nextval('evidence_seq'),
    evidence_hash   TEXT UNIQUE NOT NULL,
    file_type       VARCHAR(20)
);
COMMENT ON TABLE EvidenceCatalog IS 'Registry of valid SHA-256 evidence hashes that may be referenced by NetworkIncident.';

-- DeletedIncidentAudit (Audit Table): the spec says this must "capture
-- all attributes of deleted NetworkIncident and NodeBreachIncident
-- rows". Because those two subtypes have DIFFERENT extra columns
-- (slice_id/evidence_hashes vs node_id/assigned_investigator/
-- is_contained), a single flat audit table needs to be a superset of
-- both column sets, plus a discriminator column (incident_type) so we
-- know which subtype a given audit row came from and which of the
-- type-specific columns are meaningful for it. This is the classic
-- "single-table" approach to auditing a class hierarchy, and keeps
-- TestTriggerQueries.sql simple (one table to check, regardless of
-- which child table the DELETE happened on).
-- No FK back to Incident/children is added deliberately: once a row is
-- deleted from the live tables it must remain in the audit log forever,
-- so the audit table is intentionally decoupled from live data
-- ("immutable audit logging" per the brief).
CREATE TABLE DeletedIncidentAudit (
    audit_id                SERIAL PRIMARY KEY,
    incident_type           VARCHAR(20) NOT NULL,   -- 'NetworkIncident' | 'NodeBreachIncident'
    incident_id             INTEGER NOT NULL,
    incident_code           VARCHAR(10),
    target_ip               NodeIPType,
    severity                SeverityType,
    detected_at             TIMESTAMP,
    -- NetworkIncident-specific columns (NULL for NodeBreachIncident rows)
    slice_id                VARCHAR(20),
    evidence_hashes          TEXT[],
    -- NodeBreachIncident-specific columns (NULL for NetworkIncident rows)
    node_id                  VARCHAR(20),
    assigned_investigator    InvestigatorName,
    is_contained              BOOLEAN,
    -- Audit metadata
    deleted_at                TIMESTAMP NOT NULL DEFAULT now(),
    deleted_by                VARCHAR(50) NOT NULL
);
COMMENT ON TABLE DeletedIncidentAudit IS 'Immutable log of every row deleted from NetworkIncident or NodeBreachIncident.';

-- We deliberately do NOT create UPDATE/DELETE triggers that block
-- changes to DeletedIncidentAudit itself in this script (out of scope),
-- but in a production system "immutable" would typically also mean
-- REVOKE UPDATE, DELETE ON DeletedIncidentAudit FROM application_role;


/* =====================================================================
   3. PL/pgSQL UTILITY & VALIDATION FUNCTIONS  (8 Marks)
   ===================================================================== */

-- format_investigator_name(InvestigatorName): takes the composite UDT
-- and returns a single display string, e.g. 'Dr. Alex Mercer'.
-- We defensively trim/guard against NULL sub-fields so a partially
-- populated composite value doesn't blow up with a NULL-concatenation
-- result (in SQL, NULL || anything = NULL).
CREATE OR REPLACE FUNCTION format_investigator_name(p_investigator InvestigatorName)
RETURNS TEXT AS $$
BEGIN
    IF p_investigator IS NULL THEN
        RETURN NULL;
    END IF;

    RETURN TRIM(
        COALESCE(p_investigator.title, '') || ' ' ||
        COALESCE(p_investigator.first_name, '') || ' ' ||
        COALESCE(p_investigator.last_name, '')
    );
END;
$$ LANGUAGE plpgsql IMMUTABLE;
COMMENT ON FUNCTION format_investigator_name(InvestigatorName) IS
    'Formats an InvestigatorName composite value as "Title First Last", e.g. Dr. Alex Mercer.';

-- is_hash_registered(TEXT): a simple existence check against
-- EvidenceCatalog. Kept as its own function (rather than inlined) so it
-- can be reused both by validate_evidence_array() below and directly in
-- ad-hoc SELECT queries.
CREATE OR REPLACE FUNCTION is_hash_registered(p_hash TEXT)
RETURNS BOOLEAN AS $$
DECLARE
    v_exists BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM EvidenceCatalog WHERE evidence_hash = p_hash
    ) INTO v_exists;

    RETURN v_exists;
END;
$$ LANGUAGE plpgsql STABLE;
COMMENT ON FUNCTION is_hash_registered(TEXT) IS
    'Returns TRUE if the given hash exists in EvidenceCatalog.';

-- has_duplicate_hashes(TEXT[]): the spec explicitly asks for a nested-
-- loop implementation (rather than the one-liner
-- "array_length(x,1) <> (SELECT COUNT(DISTINCT ..))"), presumably to
-- exercise PL/pgSQL looping/array-indexing constructs. We compare every
-- element to every later element (i < j) using array indices, which is
-- the classic O(n^2) duplicate-detection pattern.
CREATE OR REPLACE FUNCTION has_duplicate_hashes(p_hashes TEXT[])
RETURNS BOOLEAN AS $$
DECLARE
    v_len INTEGER;
    i INTEGER;
    j INTEGER;
BEGIN
    IF p_hashes IS NULL THEN
        RETURN FALSE;
    END IF;

    v_len := array_length(p_hashes, 1);

    -- An empty or single-element (or NULL-length, e.g. '{}') array
    -- cannot contain a duplicate.
    IF v_len IS NULL OR v_len < 2 THEN
        RETURN FALSE;
    END IF;

    -- Nested loop: outer index i, inner index j > i, so every unordered
    -- pair {i, j} is checked exactly once.
    FOR i IN 1 .. v_len - 1 LOOP
        FOR j IN i + 1 .. v_len LOOP
            IF p_hashes[i] = p_hashes[j] THEN
                RETURN TRUE;
            END IF;
        END LOOP;
    END LOOP;

    RETURN FALSE;
END;
$$ LANGUAGE plpgsql IMMUTABLE;
COMMENT ON FUNCTION has_duplicate_hashes(TEXT[]) IS
    'Nested-loop check for duplicate values inside a hash array.';

-- validate_evidence_array(TEXT[]): composes the two functions above -
-- every hash in the array must be registered in EvidenceCatalog AND the
-- array must contain no duplicates. This is the single "gatekeeper"
-- function called by the check_evidence_integrity() trigger.
CREATE OR REPLACE FUNCTION validate_evidence_array(p_hashes TEXT[])
RETURNS BOOLEAN AS $$
DECLARE
    v_hash TEXT;
BEGIN
    -- A NULL or empty evidence array is treated as vacuously valid:
    -- an incident may be logged before any evidence has been captured.
    IF p_hashes IS NULL OR array_length(p_hashes, 1) IS NULL THEN
        RETURN TRUE;
    END IF;

    -- Reject on duplicates first (cheap check, avoids unnecessary
    -- catalog lookups).
    IF has_duplicate_hashes(p_hashes) THEN
        RETURN FALSE;
    END IF;

    -- Every hash must already be registered in EvidenceCatalog.
    FOREACH v_hash IN ARRAY p_hashes LOOP
        IF NOT is_hash_registered(v_hash) THEN
            RETURN FALSE;
        END IF;
    END LOOP;

    RETURN TRUE;
END;
$$ LANGUAGE plpgsql STABLE;
COMMENT ON FUNCTION validate_evidence_array(TEXT[]) IS
    'TRUE only if every hash in the array is registered in EvidenceCatalog and no duplicates exist.';


/* =====================================================================
   4. TRIGGER FUNCTIONS & TRIGGERS  (7 Marks)
   ===================================================================== */

-- check_evidence_integrity(): BEFORE INSERT OR UPDATE on NetworkIncident.
-- Runs BEFORE (not AFTER) so that an invalid row can be rejected before
-- it is ever written to the table - RAISE EXCEPTION inside a BEFORE
-- trigger aborts the whole INSERT/UPDATE statement/transaction.
CREATE OR REPLACE FUNCTION check_evidence_integrity()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT validate_evidence_array(NEW.evidence_hashes) THEN
        RAISE EXCEPTION
            'evidence_hashes for incident_code % contains an unregistered and/or duplicate hash: %',
            NEW.incident_code, NEW.evidence_hashes;
    END IF;

    -- Must return NEW for a BEFORE ROW trigger to allow the operation
    -- to proceed with the (possibly trigger-modified) row.
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_evidence_integrity
    BEFORE INSERT OR UPDATE ON NetworkIncident
    FOR EACH ROW
    EXECUTE FUNCTION check_evidence_integrity();

-- audit_deleted_incident(): AFTER DELETE on NetworkIncident AND
-- NodeBreachIncident. One shared trigger function, attached twice (once
-- per child table) via two CREATE TRIGGER statements below, since a
-- PostgreSQL trigger is bound to exactly one table.
--
-- TG_TABLE_NAME tells us which of the two tables fired the trigger, so
-- we branch and populate the type-specific columns accordingly, leaving
-- the columns that don't apply to that subtype as NULL. Runs AFTER
-- DELETE (not BEFORE) because we are recording history, not gating the
-- delete itself - and OLD.* is only guaranteed populated for AFTER
-- triggers on the just-deleted row.
CREATE OR REPLACE FUNCTION audit_deleted_incident()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_TABLE_NAME = 'networkincident' THEN
        INSERT INTO DeletedIncidentAudit (
            incident_type, incident_id, incident_code, target_ip, severity, detected_at,
            slice_id, evidence_hashes,
            deleted_at, deleted_by
        ) VALUES (
            'NetworkIncident', OLD.incident_id, OLD.incident_code, OLD.target_ip, OLD.severity, OLD.detected_at,
            OLD.slice_id, OLD.evidence_hashes,
            now(), CURRENT_USER
        );

    ELSIF TG_TABLE_NAME = 'nodebreachincident' THEN
        INSERT INTO DeletedIncidentAudit (
            incident_type, incident_id, incident_code, target_ip, severity, detected_at,
            node_id, assigned_investigator, is_contained,
            deleted_at, deleted_by
        ) VALUES (
            'NodeBreachIncident', OLD.incident_id, OLD.incident_code, OLD.target_ip, OLD.severity, OLD.detected_at,
            OLD.node_id, OLD.assigned_investigator, OLD.is_contained,
            now(), CURRENT_USER
        );
    END IF;

    -- Return value is ignored for AFTER triggers, but PL/pgSQL still
    -- requires a RETURN statement.
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_deleted_network_incident
    AFTER DELETE ON NetworkIncident
    FOR EACH ROW
    EXECUTE FUNCTION audit_deleted_incident();

CREATE TRIGGER trg_audit_deleted_node_breach_incident
    AFTER DELETE ON NodeBreachIncident
    FOR EACH ROW
    EXECUTE FUNCTION audit_deleted_incident();

COMMIT;
